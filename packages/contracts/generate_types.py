"""Generate TypeScript schema literals from the canonical Python JSON schemas."""

import argparse
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when generated output is stale")
    options = parser.parse_args()
    root = Path(__file__).resolve().parent
    sections = ["// Generated by packages/contracts/generate_types.py; do not edit by hand.\n"]
    for model, variable in (
        ("LiveHealth", "liveHealthSchema"),
        ("ReadyHealth", "readyHealthSchema"),
        ("ApiHealth", "apiHealthSchema"),
        ("SumoRuntimeRecord", "sumoRuntimeRecordSchema"),
        ("SystemCapabilities", "systemCapabilitiesSchema"),
        ("DiagnosticRequest", "diagnosticRequestSchema"),
        ("DiagnosticJob", "diagnosticJobSchema"),
    ):
        schema = json.loads((root / "schema" / f"{model}.json").read_text())
        sections.append(
            f"export const {variable} = {json.dumps(schema, indent=2, sort_keys=True)} as const;\n"
        )
    expected = "\n".join(sections)
    output = root / "src" / "schema.ts"
    if options.check:
        if not output.exists() or output.read_text() != expected:
            print(
                "TypeScript contracts are stale; "
                "run uv run python packages/contracts/generate_types.py"
            )
            return 1
        print("TypeScript schema literals match the canonical JSON schemas")
        return 0
    output.write_text(expected)
    print(f"Generated {output.relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
