"""Idempotently persist the explicitly synthetic M02 fixture; never import real roads."""

import asyncio
import json
from datetime import UTC, datetime
from uuid import uuid5

from geoalchemy2.shape import from_shape
from shapely.geometry import LineString, Point, shape
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from earthmind_api.dependencies import Infrastructure
from earthmind_api.fixtures import (
    BOUNDARY,
    CHECKSUM,
    DATA_SOURCE_ID,
    DEFAULT_SPEED_MPS,
    DEMAND_ID,
    EDGES,
    NAMESPACE,
    NETWORK_ID,
    NODES,
    ONE_WAY_LANES,
    REGION_ID,
    ROAD_CLASS,
    SCENARIO_ID,
    SIGNALIZED_NODE,
    SLUG,
    SYNTHETIC_METADATA,
    TWO_WAY_LANES,
    edge_id,
    node_id,
)
from earthmind_api.geospatial_models import (
    AuditEvent,
    DataSource,
    DemandProfile,
    Intersection,
    NetworkVersion,
    Region,
    RoadEdge,
    Scenario,
    ScenarioIntervention,
)
from earthmind_api.settings import Settings


async def seed(session: AsyncSession) -> dict[str, object]:
    # Serialize concurrent seeders without holding a table-wide lock.
    await session.execute(select(func.pg_advisory_xact_lock(202602)))
    existing = await session.get(NetworkVersion, NETWORK_ID)
    if existing is not None:
        if existing.checksum_sha256 != CHECKSUM:
            raise RuntimeError("Existing synthetic version has different immutable content")
        if existing.status not in {"published", "archived"} or not existing.is_validated:
            raise RuntimeError(
                "Existing fixture is not a completed published version; no data overwritten"
            )
        nodes = await session.scalar(
            select(func.count())
            .select_from(Intersection)
            .where(Intersection.network_version_id == NETWORK_ID)
        )
        edges = await session.scalar(
            select(func.count())
            .select_from(RoadEdge)
            .where(RoadEdge.network_version_id == NETWORK_ID)
        )
        if nodes != len(NODES) or edges != len(EDGES):
            raise RuntimeError(
                "Existing synthetic fixture is incomplete; preserve it for investigation"
            )
        return {
            "region_id": str(REGION_ID),
            "network_id": str(NETWORK_ID),
            "created": False,
            "nodes": nodes,
            "edges": edges,
            "is_synthetic": True,
        }
    conflict = await session.scalar(select(Region).where(Region.slug == SLUG))
    if conflict is not None and conflict.id != REGION_ID:
        raise RuntimeError("Study slug belongs to an existing user region; no data overwritten")
    if await session.get(Region, REGION_ID) is None:
        session.add(
            Region(
                id=REGION_ID,
                slug=SLUG,
                name="Downtown Dubai — Synthetic Study Region",
                country_code="AE",
                emirate="Dubai",
                timezone="Asia/Dubai",
                boundary=from_shape(shape(BOUNDARY), srid=4326),
                metadata_=dict(SYNTHETIC_METADATA),
            )
        )
    if await session.get(DataSource, DATA_SOURCE_ID) is None:
        session.add(
            DataSource(
                id=DATA_SOURCE_ID,
                provider_name="EARTHMIND",
                dataset_name="M02 project-generated synthetic study fixture",
                source_type="synthetic",
                source_url=None,
                license_identifier="LicenseRef-EARTHMIND-Proprietary-Synthetic",
                attribution_text=(
                    "Generated by the EARTHMIND project. Illustrative boundary and invented graph; "
                    "no official municipal or street accuracy claimed."
                ),
                collected_at=datetime.now(UTC),
                source_version="synthetic-v1",
                checksum_sha256=CHECKSUM,
                metadata_={
                    **SYNTHETIC_METADATA,
                    "original_manifest": {
                        "generator": "earthmind_api.fixtures",
                        "coordinate_order": "longitude_latitude",
                        "srid": 4326,
                    },
                },
            )
        )
    await session.flush()
    network = NetworkVersion(
        id=NETWORK_ID,
        region_id=REGION_ID,
        data_source_id=DATA_SOURCE_ID,
        version_label="synthetic-v1",
        status="draft",
        checksum_sha256=CHECKSUM,
        artifact_uri="synthetic://earthmind/m02/dubai-downtown-demo/v1",
        source_format="synthetic_geojson",
        projection_srid=4326,
        node_count=len(NODES),
        edge_count=len(EDGES),
        is_validated=False,
        validation_summary={"status": "NOT_VALIDATED", "is_synthetic": True},
    )
    session.add(network)
    await session.flush()
    coordinates = {}
    for name, longitude, latitude in NODES:
        coordinates[name] = (longitude, latitude)
        session.add(
            Intersection(
                id=node_id(name),
                network_version_id=NETWORK_ID,
                source_node_id=f"synthetic:{name}",
                sumo_node_id=None,
                location=from_shape(Point(longitude, latitude), srid=4326),
                intersection_type="synthetic_junction",
                is_signalized=name == SIGNALIZED_NODE,
                metadata_={
                    **SYNTHETIC_METADATA,
                    "signal_status": "simulated" if name == SIGNALIZED_NODE else "not_simulated",
                    "sumo_identifier_verified": False,
                },
            )
        )
    await session.flush()
    for name, start, end, one_way in EDGES:
        session.add(
            RoadEdge(
                id=edge_id(name),
                network_version_id=NETWORK_ID,
                start_intersection_id=node_id(start),
                end_intersection_id=node_id(end),
                sumo_edge_id=f"provisional:{name}",
                source_edge_id=f"synthetic:{name}",
                name=f"Synthetic link {name}",
                road_class=ROAD_CLASS,
                geom=from_shape(LineString([coordinates[start], coordinates[end]]), srid=4326),
                lane_count=ONE_WAY_LANES if one_way else TWO_WAY_LANES,
                speed_limit_mps=DEFAULT_SPEED_MPS,
                is_one_way=one_way,
                metadata_={**SYNTHETIC_METADATA, "sumo_identifier_verified": False},
            )
        )
    await session.flush()
    # Imported here to avoid model/service module cycles.
    from earthmind_api.network_validation import validate_network

    report = await validate_network(session, NETWORK_ID)
    if report.get("status") not in {"VALID", "VALID_WITH_WARNINGS"}:
        raise RuntimeError(f"Synthetic fixture validation failed: {json.dumps(report)}")
    network.validation_summary = {**report, "is_synthetic": True}
    network.is_validated = True
    network.status = "published"
    await session.flush()
    session.add(
        DemandProfile(
            id=DEMAND_ID,
            network_version_id=NETWORK_ID,
            name="Synthetic M02 persistence contract",
            seed=202602,
            profile_type="synthetic",
            config={
                "is_synthetic": True,
                "execution_enabled": False,
                "purpose": "schema fixture only",
            },
            artifact_uri=None,
        )
    )
    await session.flush()
    session.add(
        Scenario(
            id=SCENARIO_ID,
            network_version_id=NETWORK_ID,
            demand_profile_id=DEMAND_ID,
            name="Synthetic M02 scenario contract",
            description="Persistence fixture only; no traffic simulation was executed.",
            duration_seconds=60,
            config={"is_synthetic": True, "execution_enabled": False},
            created_by=None,
        )
    )
    await session.flush()
    session.add(
        ScenarioIntervention(
            id=uuid5(NAMESPACE, "intervention:synthetic-speed"),
            scenario_id=SCENARIO_ID,
            intervention_type="speed_limit",
            target_identifier="provisional:e0",
            parameters={"is_synthetic": True, "speed_limit_mps": 6.0, "executed": False},
        )
    )
    session.add(
        AuditEvent(
            id=uuid5(NAMESPACE, "audit:synthetic-seed"),
            actor_id=None,
            action="seed_synthetic_fixture",
            target_type="network_version",
            target_id=NETWORK_ID,
            metadata_={"is_synthetic": True, "checksum_sha256": CHECKSUM},
        )
    )
    await session.flush()
    return {
        "region_id": str(REGION_ID),
        "network_id": str(NETWORK_ID),
        "created": True,
        "nodes": len(NODES),
        "edges": len(EDGES),
        "is_synthetic": True,
    }


async def main() -> None:
    infrastructure = Infrastructure(Settings())
    try:
        async with infrastructure.session() as session:
            result = await seed(session)
        print(json.dumps(result, sort_keys=True))
    finally:
        await infrastructure.close()


if __name__ == "__main__":
    asyncio.run(main())
